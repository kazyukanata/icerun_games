let currentStage = 0;
let map = stages[currentStage].map;
let player = findStart(map);

function findStart(map) {
  for (let y = 0; y < map.length; y++) {
    for (let x = 0; x < map[0].length; x++) {
      if (map[y][x] === 2) return { x, y };
    }
  }
  return { x: 1, y: 1 };
}

function loadStage(n) {
  if (n < 0) n = 0;
  if (n >= stages.length) {
    alert("全ステージクリア！");
    n = stages.length - 1;
  }
  currentStage = n;
  map = stages[currentStage].map;

  const size = stages[currentStage].size;
  const game = document.getElementById("game");
  game.style.gridTemplateColumns = `repeat(${size}, 40px)`;
  game.style.gridTemplateRows = `repeat(${size}, 40px)`;

  document.getElementById("stageInfo").textContent =
    `ステージ ${currentStage + 1} / ${stages.length}`;

  player = findStart(map);
  draw();
}

function draw() {
  const game = document.getElementById("game");
  game.innerHTML = "";

  for (let y = 0; y < map.length; y++) {
    for (let x = 0; x < map[0].length; x++) {
      let div = document.createElement("div");
      div.classList.add("tile");

      if (player.x === x && player.y === y) {
        div.classList.add("player");
      } else {
        if (map[y][x] === 0) div.classList.add("ice");
        if (map[y][x] === 1) div.classList.add("wall");
        if (map[y][x] === 2) div.classList.add("start");
        if (map[y][x] === 3) div.classList.add("goal");
        if (map[y][x] === 4) div.classList.add("switch");
        if (map[y][x] === 5) div.classList.add("wallOn");
        if (map[y][x] === 6) div.classList.add("wallOff");
      }

      game.appendChild(div);
    }
  }
}

function move(dir) {
  let dx = 0, dy = 0;
  if (dir === "up") dy = -1;
  if (dir === "down") dy = 1;
  if (dir === "left") dx = -1;
  if (dir === "right") dx = 1;

  while (true) {
    let nx = player.x + dx;
    let ny = player.y + dy;

    if (ny < 0 || ny >= map.length || nx < 0 || nx >= map[0].length) break;

    let tile = map[ny][nx];

    // 壁・ON壁で停止
    if (tile === 1 || tile === 5) break;

    // スイッチを踏んだら可動壁を切り替え
    if (tile === 4) {
      toggleWalls();
    }

    player.x = nx;
    player.y = ny;

    if (tile === 3) {
      alert("クリア！");
      loadStage(currentStage + 1);
      return;
    }
  }

  draw();
}

function toggleWalls() {
  for (let y = 0; y < map.length; y++) {
    for (let x = 0; x < map[0].length; x++) {
      if (map[y][x] === 5) map[y][x] = 6;
      else if (map[y][x] === 6) map[y][x] = 5;
    }
  }
}

function resetStage() {
  player = findStart(map);
  draw();
}

loadStage(0);
